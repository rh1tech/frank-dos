#!/usr/bin/env python3
"""FRANK DOS: assemble the BIOS ROM (src/hle/rom.asm) into a C array.

    mkrom.py rom.asm rom_layout.h out.c

rom_layout.h's #defines become nasm equates (rom_layout.inc, next to out.c),
nasm builds the 64 KB image, and out.c holds it as hle_rom_image[].
"""
import os
import re
import subprocess
import sys

asm, layout, out = sys.argv[1:4]
work = os.path.dirname(os.path.abspath(out))
os.makedirs(work, exist_ok=True)

with open(layout) as f, open(os.path.join(work, 'rom_layout.inc'), 'w') as inc:
    for line in f:
        m = re.match(r'#define\s+([A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|\d+)u?\b', line)
        if m:
            inc.write('%s equ %s\n' % (m.group(1), m.group(2)))

binpath = os.path.join(work, 'rom.bin')
subprocess.check_call(['nasm', '-f', 'bin', '-I', work + '/', '-o', binpath, os.path.abspath(asm)], cwd=work)
data = open(binpath, 'rb').read()
if len(data) != 65536:
    sys.exit('rom.bin is %d bytes, not 65536' % len(data))

with open(out, 'w') as f:
    f.write('/* generated by tools/mkrom.py from src/hle/rom.asm */\n#include <stdint.h>\n')
    f.write('const uint8_t hle_rom_image[65536] = {\n')
    for i in range(0, len(data), 16):
        f.write('\t' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',\n')
    f.write('};\n')

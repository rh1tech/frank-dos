#define EXEC1_COLD_H

#define EXEC1_SECOND(a, b, ...) b
#define EXEC1_PROBE_(...) EXEC1_SECOND(__VA_ARGS__, 0, 0)
#define EXEC1_COLD_PROBE ~, 1
#define EXEC1_IS_COLD(op) EXEC1_PROBE_(EXEC1_COLD_ ## op)


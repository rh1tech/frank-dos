/*
 * The COLD set: opcodes the SRAM copy of cpu_exec1 hands to the flash copy
 * (i386.c, exec1.inc). Rare in what runs here (DOS games in real mode, DOS
 * extenders, Win95) by the opcode counts on FRANK Next; each one costs a call
 * into flash when it does run.
 *
 * EXEC1_IS_COLD(op) is 1 for a name defined below as EXEC1_COLD_PROBE, 0 for
 * any other (the preprocessor's "is it defined" idiom: no table to keep in
 * step with i386ins.def).
 */
